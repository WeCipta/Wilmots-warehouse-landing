  const wink = () => {
    const eye = eyeRef.current;
    if (!eye) return;
    gsap.killTweensOf(eye);
    gsap.to(eye, {
      attr: { ry: 0.9 },
      duration: 0.12,
      ease: "power2.out",
    });
  };

  const unWink = () => {
    const eye = eyeRef.current;
    if (!eye) return;
    gsap.killTweensOf(eye);
    gsap.to(eye, {
      attr: { ry: 7.16769 },
      duration: 0.18,
      ease: "power2.out",
    });
  };

